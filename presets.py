def preset_choices(lang='ar'):
    """قائمة مبسطة للقوائم المنسدلة (id, الاسم, الوصف, عدد الخدمات)."""
    en = lang == 'en'
    return [{'id': k, 'icon': v['icon'], 'name': v['en' if en else 'ar'],
             'desc': v['desc_en' if en else 'desc_ar'], 'count': len(v['services'])}
            for k, v in PRESETS.items()]
